// Generates src/components/tokens.css: the colours of the Settings and setup windows (0.6), from
// the design lab's palettes (design-lab/reglages/src/tokens/palettes.js): the neutral base
// « Porcelaine & lavande » and the page colours of set A (« vives »), light and dark, each tuned
// for contrast by the lab's own maths. Run `node scripts/gen-ft-tokens.mjs`, then commit the file.
//
// Selectors: :root (light), :root[data-theme="dark"] (src/theme.ts writes the resolved theme),
// and [data-ft-page="<id>"] for the page colours. Before the script runs, the media query stands in.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PALETTE_BY_ID, PILL_ALPHA, pageColor, paletteVars, rgbTriplet } from '../design-lab/reglages/src/tokens/palettes.js';

const base = 'porcelaine';
const set = 'A';
// Lab page id → app page id (src/types.ts settingsPages).
const pages = { general: 'general', raccourcis: 'shortcuts', actions: 'actions', apres: 'after', apparence: 'appearance', serveur: 'server', donnees: 'data', diagnostic: 'diagnostic' };

const palette = PALETTE_BY_ID[base];
const vars = theme => Object.entries(paletteVars(palette, theme))
  // The wallpaper and the tile colours are the lab's decor: the app has neither.
  .filter(([name]) => !/^--ft-(wall|tile|on-tile)-/.test(name) && name !== '--ft-scheme')
  .map(([name, value]) => `  ${name}: ${value};`).join('\n');
const page = (id, theme) => {
  const colour = pageColor(set, id, base, theme);
  const rgb = rgbTriplet(colour.hue);
  return `--ft-page: ${colour.hue}; --ft-page-rgb: ${rgb}; --ft-page-text: ${colour.text}; --ft-page-soft: rgb(${rgb} / ${PILL_ALPHA[theme]}); --ft-page-veil: rgb(${rgb} / ${theme === 'dark' ? 0.13 : 0.09});`;
};
const pageRules = (theme, prefix) => Object.entries(pages).map(([lab, app]) => `${prefix}[data-ft-page="${app}"] { ${page(lab, theme)} }`).join('\n');
const indent = text => text.split('\n').map(line => `  ${line}`).join('\n');

const css = `/* GENERATED by scripts/gen-ft-tokens.mjs from design-lab/reglages/src/tokens/palettes.js. Do not edit.
   Base « ${palette.long} », page colours of set ${set}; contrast rules in the lab (scripts/contrast.mjs). */
:root {
${vars('light')}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${indent(vars('dark'))}
  }
${indent(pageRules('dark', ':root:not([data-theme="light"]) '))}
}
:root[data-theme="dark"] {
${vars('dark')}
}
${pageRules('light', '')}
${pageRules('dark', ':root[data-theme="dark"] ')}
`;
const target = fileURLToPath(new URL('../src/components/tokens.css', import.meta.url));
writeFileSync(target, css);
console.log(`${target}: ${css.length} bytes`);
